/**
 * Localize English templates that were hardcoded into stored patient/episode/plan
 * fields at onboarding time (e.g. "Sara's family member", "Support requested: …").
 * Does not rewrite the database — display-only.
 */

import i18n from '@/i18n/config';
import { familyEnumLabel } from '@/lib/familyLanguage';

function isArabic(): boolean {
  return (i18n.language || '').toLowerCase().startsWith('ar');
}

function coord(key: string, fallback: string, opts?: Record<string, string | number>): string {
  const translated = i18n.t(key, { ns: 'coordinator', defaultValue: '', ...opts });
  if (translated && translated !== key) return translated;
  return fallback;
}

/** Display names / titles generated by derivePatientName / deriveCareUnitName / episode create. */
export function localizeGeneratedLabel(raw?: string | null): string {
  if (!raw) return '';
  let text = raw;

  // Normalize curly/smart apostrophes from pasted names.
  text = text.replace(/[\u2019\u2018]/g, "'");

  text = text.replace(
    /^AI Draft — Care episode — /i,
    coord('display.aiDraftEpisodePrefix', 'AI Draft — Care episode — '),
  );
  text = text.replace(/^AI Draft — /i, coord('display.aiDraftPrefix', 'AI Draft — '));
  text = text.replace(/^Care episode — /i, coord('display.careEpisodePrefix', 'Care episode — '));
  text = text.replace(/^Care episode - /i, coord('display.careEpisodePrefix', 'Care episode — '));

  const familyMemberSuffix = coord('display.familyMemberSuffix', "'s family member");
  text = text.replace(/'s family member\b/gi, familyMemberSuffix);
  // Bare phrase without possessive (rare / mid-sentence).
  if (isArabic()) {
    text = text.replace(/\bfamily member\b/gi, coord('display.familyMemberBare', 'فرد من العائلة'));
  }

  text = text.replace(/'s Family Care\b/gi, coord('display.familyCareSuffix', "'s Family Care"));
  text = text.replace(/'s Care\b/gi, coord('display.careSuffix', "'s Care"));
  text = text.replace(/'s client\b/gi, coord('display.clientSuffix', "'s client"));

  if (/^Family care recipient$/i.test(text)) {
    return coord('display.familyCareRecipient', 'Family care recipient');
  }
  if (/^Care recipient$/i.test(text)) {
    return coord('display.careRecipient', 'Care recipient');
  }

  return text;
}

const REASON_PHRASE_MAP: Array<[RegExp, string, string]> = [
  [/^Support requested:\s*/i, 'display.supportRequested', 'Support requested: '],
  [/Preferred schedule:\s*/gi, 'display.preferredSchedule', 'Preferred schedule: '],
  [/Care location preference:\s*/gi, 'display.careLocationPref', 'Care location preference: '],
  [/Provider gender preference:\s*/gi, 'display.providerGenderPref', 'Provider gender preference: '],
  [/Provider languages:\s*/gi, 'display.providerLanguages', 'Provider languages: '],
  [
    /Family requested care support via simple onboarding\. Clinical details pending coordinator review\./i,
    'display.pendingClinicalNotes',
    'Family requested care support via simple onboarding. Clinical details pending coordinator review.',
  ],
  [
    /Created from family simple onboarding\. Clinical details pending coordinator review/i,
    'display.createdFromOnboarding',
    'Created from family simple onboarding. Clinical details pending coordinator review',
  ],
];

const TOKEN_GROUPS = ['support', 'need', 'schedule', 'careLocation', 'gender', 'day', 'time'] as const;

function localizeToken(token: string): string {
  const trimmed = token.trim();
  if (!trimmed) return trimmed;
  for (const group of TOKEN_GROUPS) {
    const via = familyEnumLabel(group, trimmed);
    if (via !== trimmed.replace(/_/g, ' ') && via !== trimmed) return via;
  }
  const slug = trimmed.toLowerCase().replace(/[\s-]+/g, '_');
  const svc = i18n.t(`intake.services.${slug}`, { ns: 'coordinator', defaultValue: '' });
  if (svc && svc !== `intake.services.${slug}`) return svc;
  const urg = i18n.t(`intake.urgency.${slug}`, { ns: 'coordinator', defaultValue: '' });
  if (urg && urg !== `intake.urgency.${slug}`) return urg;
  const chip = i18n.t(`chips.${slug}`, { ns: 'coordinator', defaultValue: '' });
  if (chip && chip !== `chips.${slug}`) return chip;
  const langMap: Record<string, string> = {
    english: 'الإنجليزية',
    arabic: 'العربية',
    french: 'الفرنسية',
    urdu: 'الأردية',
    hindi: 'الهندية',
  };
  if (isArabic() && langMap[slug]) return langMap[slug];
  return trimmed.replace(/_/g, ' ');
}

/** Localize stored reasonForCare / notes / revision English templates + enum tokens. */
export function localizeStoredNarrative(raw?: string | null): string {
  if (!raw) return '';
  let text = localizeGeneratedLabel(raw);
  for (const [re, key, fallback] of REASON_PHRASE_MAP) {
    text = text.replace(re, coord(key, fallback));
  }

  if (isArabic()) {
    text = text.replace(/\bdiagnoses\b/gi, coord('display.diagnosesWord', 'التشخيصات'));
    text = text.replace(/\bdiagnosis\b/gi, coord('display.diagnosisWord', 'التشخيص'));
  }

  // Localize known category labels and snake_case tokens inside the narrative.
  text = text.replace(/\b([a-z]+(?:_[a-z]+)+)\b/gi, (m) => localizeToken(m));
  text = text.replace(
    /\b(Home Care|Home Visit|Babysitting|Therapy|Disability|Personal care|Companionship)\b/gi,
    (m) => localizeToken(m),
  );
  text = text.replace(
    /\b(one_time|weekly|daily|flexible|home|clinic|telehealth|male_only|female_only|no_preference|both)\b/gi,
    (m) => localizeToken(m),
  );

  return text;
}

/** Timeline / review chips (concerns, risk flags, freeform tags). */
export function localizeChip(raw: string): string {
  return localizeToken(raw);
}

/** Care-plan frequency lines like "1 session per week · 60min". */
export function localizeFrequencyLine(raw?: string | null): string {
  if (!raw) return '';
  let text = raw;
  const pairs: Array<[RegExp, string, string]> = [
    [/sessions?\s*per\s*week/gi, 'display.sessionPerWeek', 'session per week'],
    [/days?\s*per\s*week/gi, 'display.daysPerWeek', 'days per week'],
    [/sessions?\s*per\s*month/gi, 'display.sessionPerMonth', 'session per month'],
    [/days?\s*per\s*month/gi, 'display.daysPerMonth', 'days per month'],
    [/per\s*week/gi, 'display.perWeek', 'per week'],
    [/per\s*month/gi, 'display.perMonth', 'per month'],
    [/(\d+)\s*mins?\b/gi, 'display.minutes', '$1 min'],
  ];
  for (const [re, key, fallback] of pairs) {
    if (key === 'display.minutes') {
      text = text.replace(re, (_, n) => {
        const out = coord(key, fallback, { count: n });
        return out.includes('{{count}}') ? out.replace(/\{\{count\}\}/g, String(n)) : out;
      });
    } else if (key === 'display.sessionPerWeek') {
      // Prefer plural-aware key when source said "sessions".
      text = text.replace(re, (m) =>
        /sessions/i.test(m)
          ? coord('display.sessionsPerWeek', 'sessions per week')
          : coord('display.sessionPerWeek', 'session per week'),
      );
    } else if (key === 'display.daysPerWeek') {
      text = text.replace(re, (m) =>
        /days/i.test(m)
          ? coord('display.daysPerWeek', 'days per week')
          : coord('display.dayPerWeek', 'day per week'),
      );
    } else if (key === 'display.sessionPerMonth') {
      text = text.replace(re, (m) =>
        /sessions/i.test(m)
          ? coord('display.sessionsPerMonth', 'sessions per month')
          : coord('display.sessionPerMonth', 'session per month'),
      );
    } else {
      text = text.replace(re, coord(key, fallback));
    }
  }
  if (isArabic()) {
    text = text.replace(/\bQAR\b/g, coord('display.currencyQar', 'ر.ق.'));
  }
  return text;
}

export function localizeAccountTypeLabel(label?: string | null): string {
  if (!label) return '';
  const map: Record<string, string> = {
    'Family Guardian': 'family_member',
    'Individual (for myself)': 'myself',
    'Support Coordinator': 'support_coordinator',
    myself: 'myself',
    family_member: 'family_member',
    support_coordinator: 'support_coordinator',
  };
  const slug = map[label] ?? label;
  return familyEnumLabel('account', slug) !== slug.replace(/_/g, ' ')
    ? familyEnumLabel('account', slug)
    : coord(`display.account.${slug}`, label);
}
